"""
Generates the "Health Assistance Summary" PDF described in the spec.
Uses fpdf2 (lightweight, pure-Python, no system dependencies) so the
mini-project stays easy to set up.
"""
import io
from datetime import datetime
from fpdf import FPDF

GREEN_DARK = (49, 92, 72)
GREEN_LIGHT = (223, 235, 226)
TEXT = (38, 53, 45)


class MediMatePDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 18)
        self.set_text_color(*GREEN_DARK)
        self.cell(0, 12, "MediMate", ln=True)
        self.set_font("Helvetica", "", 11)
        self.set_text_color(*TEXT)
        self.cell(0, 8, "Health Assistance Summary", ln=True)
        self.set_font("Helvetica", "", 9)
        self.cell(0, 6, datetime.now().strftime("%d %B %Y, %I:%M %p"), ln=True)
        self.ln(4)
        self.set_draw_color(*GREEN_LIGHT)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(6)

    def section_title(self, title):
        self.set_x(self.l_margin)
        self.set_font("Helvetica", "B", 12)
        self.set_text_color(*GREEN_DARK)
        self.cell(0, 8, title, ln=True)
        self.set_font("Helvetica", "", 10.5)
        self.set_text_color(*TEXT)

    def bullet(self, text):
        self.set_x(self.l_margin)
        self.multi_cell(0, 6, f"  -  {text}")

    def cell(self, *args, **kwargs):
        self.set_x(self.l_margin)
        return super().cell(*args, **kwargs)

    def multi_cell(self, *args, **kwargs):
        self.set_x(self.l_margin)
        return super().multi_cell(*args, **kwargs)


def generate_pdf(user_input: str, analysis: dict, remedies: list) -> bytes:
    pdf = MediMatePDF()
    pdf.add_page()

    pdf.section_title("Your Message")
    pdf.multi_cell(0, 6, user_input or "-")
    pdf.ln(2)

    pdf.section_title("NLP Analysis")
    active = analysis.get("active_symptoms", [])
    pdf.bullet("Detected symptoms: " + (", ".join(s["label"] for s in active) or "none"))
    pdf.bullet("Duration: " + (analysis.get("duration") or "not mentioned"))
    pdf.bullet("Severity: " + (analysis.get("severity") or "not mentioned"))
    pdf.bullet("Intent: " + analysis.get("intent", "-").replace("_", " "))
    pdf.bullet(f"Confidence: {analysis.get('confidence', '-')}%")
    pdf.ln(2)

    pdf.section_title("Suggested Remedies & General OTC Information")
    if not remedies:
        pdf.multi_cell(0, 6, "No specific remedies matched.")
    for r in remedies:
        pdf.set_font("Helvetica", "B", 10.5)
        pdf.cell(0, 7, r["label"], ln=True)
        pdf.set_font("Helvetica", "", 10.5)
        for line in r["remedies"]:
            pdf.bullet(line)
        pdf.multi_cell(0, 6, f"OTC info: {r['otc']}")
        pdf.multi_cell(0, 6, f"Seek care if: {r['warning_signs']}")
        pdf.ln(2)

    pdf.section_title("Medical Disclaimer")
    pdf.multi_cell(
        0, 6,
        "MediMate provides general health information generated by a student "
        "NLP project and is not a substitute for professional medical advice, "
        "diagnosis, or treatment. Always consult a qualified healthcare "
        "provider for any medical concerns."
    )

    return bytes(pdf.output(dest="S"))
